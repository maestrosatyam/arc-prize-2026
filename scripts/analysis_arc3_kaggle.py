"""Analysis of the ARC-AGI-3 Kaggle commit runs (25 public games x 4 passes each) from their benchmark.json files.

Outputs experiments/arc3-kaggle-analysis/{summary.md, per_pass.csv, table.json}. Pure stdlib.

  python3 -I scripts/analysis_arc3_kaggle.py
"""
from __future__ import annotations

import csv
import itertools
import json
import math
import random
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ["P0", "I3", "I3b", "I5", "I6", "I7"]
OUT = ROOT / "experiments" / "arc3-kaggle-analysis"
CRIT = {5: 3.06, 6: 2.77, 7: 2.57}  # F(k-1, 3k) 5% critical values
BUDGETS = [10_000, 25_000, 50_000, 75_000, 100_000, 150_000, 200_000, 250_000, 300_000, 400_000]


def game_score(apl: list[int], base: list[int], cleared: int) -> float:
    n = len(base)
    w = n * (n + 1) / 2
    s = cap = 0.0
    for i in range(cleared):
        a = apl[i]
        s += (i + 1) * (min(1.15, (base[i] / a) ** 2) if a > 0 else 0.0)
        cap += i + 1
    return 100 * min(s / w, cap / w)


def load(tag: str) -> list[dict]:
    b = json.loads((ROOT / "experiments" / "runs" / f"kaggle-{tag}-commit-v1" / "benchmark.json").read_text())
    rows = []
    seen: dict[str, int] = {}
    for r in b["game_runs"]:
        g = r["game_id"].split("-")[0]
        p = seen.get(g, 0)
        seen[g] = p + 1
        h = r["history"]
        cumtok, t = [], 0
        for x in h:
            t += int(x.get("generated_tokens") or 0)
            cumtok.append(t)
        apl, base, lc = r["actions_per_level"], r["base_actions_per_level"], r["levels_completed"]
        assert abs(game_score(apl, base, lc) - r["final_score"]) < 1e-6
        clear_idx = list(itertools.accumulate(apl[:lc]))  # action count at which each cleared level finished
        clear_tok = [cumtok[min(len(cumtok), c) - 1] if cumtok else 0 for c in clear_idx]
        eff = [min(1.15, (base[i] / apl[i]) ** 2) for i in range(lc) if apl[i] > 0]
        rows.append({
            "run": tag, "game": g, "pass": p, "levels": len(base), "cleared": lc, "won": r["state"] == "won",
            "score": r["final_score"], "actions": len(h), "tokens_logged": t,
            "tokens_note": int(str(r.get("solver_note", "")).split("tokens=")[-1]) if "tokens=" in str(r.get("solver_note", "")) else None,
            "wall_s": r.get("final_wallclock_seconds"), "mean_level_eff": (sum(eff) / len(eff)) if eff else None,
            "apl": apl, "base": base, "clear_tok": clear_tok,
        })
    return rows


def score_at_budget(row: dict, budget: int) -> float:
    k = sum(1 for t in row["clear_tok"] if t <= budget)
    return game_score(row["apl"], row["base"], k)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    data = {tag: load(tag) for tag in RUNS}
    games = sorted({r["game"] for r in data["P0"]})

    with (OUT / "per_pass.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["run", "game", "pass", "levels", "cleared", "won", "score", "actions", "tokens_logged", "tokens_note", "wall_s", "mean_level_eff"])
        for tag in RUNS:
            for r in sorted(data[tag], key=lambda x: (x["game"], x["pass"])):
                w.writerow([tag, r["game"], r["pass"], r["levels"], r["cleared"], int(r["won"]), round(r["score"], 3), r["actions"],
                            r["tokens_logged"], r["tokens_note"], round(r["wall_s"] or 0, 1),
                            None if r["mean_level_eff"] is None else round(r["mean_level_eff"], 4)])

    L: list[str] = []
    T: dict = {}
    L.append("# ARC-AGI-3 Kaggle commit runs: per-pass analysis\n")
    L.append("Source: `experiments/runs/kaggle-{P0,I3,I3b,I5,I6}-commit-v1/benchmark.json` (25 public games x 4 passes per run; "
             "official per-level formula reproduces every recorded game score exactly). Generated by `scripts/analysis_arc3_kaggle.py`.\n")

    # 1. run-level table
    L.append("## 1. Runs\n")
    L.append("| Run | Mean score | Pass means | Levels cleared (sum of pass means) | Games won / 100 | Mean efficiency of cleared levels | Tokens per game-pass (logged) | Actions per game-pass |")
    L.append("|---|---|---|---|---|---|---|---|")
    passmeans = {}
    for tag in RUNS:
        rows = data[tag]
        pm = [st.mean(r["score"] for r in rows if r["pass"] == p) for p in range(4)]
        passmeans[tag] = pm
        eff = [r["mean_level_eff"] for r in rows if r["mean_level_eff"] is not None]
        T.setdefault("runs", {})[tag] = {"mean": st.mean(r["score"] for r in rows), "pass_means": pm,
                                         "levels": sum(r["cleared"] for r in rows) / 4, "won": sum(r["won"] for r in rows),
                                         "mean_eff": st.mean(eff), "tokens": st.mean(r["tokens_logged"] for r in rows),
                                         "actions": st.mean(r["actions"] for r in rows)}
        R = T["runs"][tag]
        L.append(f"| {tag} | {R['mean']:.2f} | {', '.join(f'{x:.1f}' for x in pm)} | {R['levels']:.1f} | {R['won']} | {R['mean_eff']:.3f} | {R['tokens']/1e3:.0f}k | {R['actions']:.0f} |")

    # 2. variance decomposition
    L.append("\n## 2. Noise: is any run different from the others beyond pass-to-pass variation?\n")
    allpm = [x for tag in RUNS for x in passmeans[tag]]
    within = st.mean([st.variance(passmeans[tag]) for tag in RUNS])
    runmeans = [st.mean(passmeans[tag]) for tag in RUNS]
    between = 4 * st.variance(runmeans)
    F = between / within
    T["anova"] = {"within_pass_mean_sd": math.sqrt(within), "sd_run_mean_expected": math.sqrt(within / 4),
                  "sd_run_mean_observed": st.stdev(runmeans), "F": F, "df": [4, 15]}
    L.append(f"Each pass is an independent replicate of all 25 games, so every run gives four replicate means. "
             f"Pooled within-run SD of a pass mean: **{math.sqrt(within):.2f}**; expected SD of a 4-pass run mean if all runs were identical: "
             f"**{math.sqrt(within/4):.2f}**; observed SD of the {len(RUNS)} run means: **{st.stdev(runmeans):.2f}**. "
             f"One-way ANOVA on the {4*len(RUNS)} pass means: F = {F:.2f} with ({len(RUNS)-1}, {3*len(RUNS)}) degrees of freedom "
             f"(the 5% critical value is {CRIT.get(len(RUNS), float('nan')):.2f}).\n")

    # permutation tests, game-paired at pass level
    rnd = random.Random(0)
    L.append("Game-paired permutation tests at pass level (within each game, the 8 pass scores of P0 and the variant are relabelled; 20,000 draws):\n")
    L.append("| Variant | Mean Δ vs P0 | Two-sided p |")
    L.append("|---|---|---|")
    p0 = {g: [r["score"] for r in data["P0"] if r["game"] == g] for g in games}
    for tag in RUNS[1:]:
        x = {g: [r["score"] for r in data[tag] if r["game"] == g] for g in games}
        obs = st.mean(st.mean(x[g]) - st.mean(p0[g]) for g in games)
        cnt = 0
        for _ in range(20000):
            tot = 0.0
            for g in games:
                pool = p0[g] + x[g]
                rnd.shuffle(pool)
                tot += st.mean(pool[4:]) - st.mean(pool[:4])
            if abs(tot / len(games)) >= abs(obs) - 1e-12:
                cnt += 1
        pval = (cnt + 1) / 20001
        T.setdefault("perm", {})[tag] = {"delta": obs, "p": pval}
        L.append(f"| {tag} | {obs:+.2f} | {pval:.3f} |")
    L.append("\nNo correction for multiple comparisons is applied; with four comparisons a Bonferroni threshold would be 0.0125.\n")

    # per-game between-pass SD
    sdg = {g: st.stdev(p0[g]) for g in games}
    L.append(f"Per-game SD between the four P0 passes: median {st.median(sdg.values()):.1f}, max {max(sdg.values()):.1f} "
             f"({max(sdg, key=sdg.get)}). Games with all four P0 passes at 0: {', '.join(g for g in games if max(p0[g]) == 0) or 'none'}.\n")

    # 3. anytime curve
    L.append("## 3. Anytime curve: score if each game-pass had stopped at a token budget\n")
    L.append("Computed by truncating each recorded game-pass at a cumulative generated-token budget and counting only levels cleared within it. "
             "This is a lower bound on what a shorter run would score (a real shorter run would not have spent tokens on the levels it later abandoned), "
             "and it cannot extrapolate beyond the tokens actually spent.\n")
    L.append("| Budget (tokens per game-pass) | " + " | ".join(RUNS) + " | Elasticity (P0, vs previous budget) |")
    L.append("|---|" + "---|" * len(RUNS) + "---|")
    prev = None
    curve = {}
    for bud in BUDGETS:
        vals = {tag: st.mean(score_at_budget(r, bud) for r in data[tag]) for tag in RUNS}
        curve[bud] = vals
        el = ""
        if prev is not None and prev[1] > 0 and vals["P0"] > 0:
            el = f"{math.log(vals['P0'] / prev[1]) / math.log(bud / prev[0]):.2f}"
        L.append(f"| {bud/1e3:.0f}k | " + " | ".join(f"{vals[t]:.2f}" for t in RUNS) + f" | {el} |")
        prev = (bud, vals["P0"])
    T["anytime"] = {str(k): v for k, v in curve.items()}
    med_tok = st.median(r["tokens_logged"] for r in data["P0"])
    L.append(f"\nMedian logged tokens per P0 game-pass: {med_tok/1e3:.0f}k (logged tokens are attributed to executed actions; the harness's own counter, "
             f"which includes tokens after the last action, is higher).\n")

    # 3b. were unfinished games still progressing when they ran out of time?
    L.append("### Unfinished games: score at a fraction of their own tokens\n")
    L.append("For game-passes that did not win (they ran until their time share ended), score if they had stopped at a fraction of the tokens they actually used. "
             "A curve still rising at 100% means those games were still earning levels when time ran out.\n")
    fr = [0.5, 0.6, 0.7, 0.8, 0.9, 1.0]
    L.append("| Run | n | " + " | ".join(f"{int(f*100)}%" for f in fr) + " | Elasticity 80->100% |")
    L.append("|---|---|" + "---|" * len(fr) + "---|")
    T["unfinished"] = {}
    for tag in RUNS:
        rows = [r for r in data[tag] if not r["won"] and r["tokens_logged"] > 0]
        vals = [st.mean(score_at_budget(r, f * r["tokens_logged"]) for r in rows) for f in fr]
        el = math.log(vals[-1] / vals[3]) / math.log(1 / 0.8) if vals[3] > 0 else float("nan")
        last_clear = [ (r["clear_tok"][-1] / r["tokens_logged"]) for r in rows if r["clear_tok"] ]
        T["unfinished"][tag] = {"n": len(rows), "curve": dict(zip(map(str, fr), vals)), "elasticity_80_100": el,
                                "median_frac_tokens_at_last_clear": st.median(last_clear) if last_clear else None}
        L.append(f"| {tag} | {len(rows)} | " + " | ".join(f"{v:.2f}" for v in vals) + f" | {el:.2f} |")
    lc = T["unfinished"]["P0"]["median_frac_tokens_at_last_clear"]
    L.append(f"\nIn P0's unfinished game-passes, the last level was cleared at a median of {lc:.0%} of the tokens the game-pass eventually used.\n")

    # 4. where the score comes from
    L.append("## 4. Levels versus efficiency\n")
    L.append("| Run | Levels cleared per pass | Mean level efficiency (min(1.15,(h/a)^2)) on cleared levels | Share of cleared levels at or above human efficiency |")
    L.append("|---|---|---|---|")
    for tag in RUNS:
        effs = [min(1.15, (r["base"][i] / r["apl"][i]) ** 2) for r in data[tag] for i in range(r["cleared"]) if r["apl"][i] > 0]
        share = sum(1 for e in effs if e >= 1.0) / len(effs)
        L.append(f"| {tag} | {T['runs'][tag]['levels']:.1f} | {st.mean(effs):.3f} | {share:.0%} |")
    by_level = {}
    for r in data["P0"]:
        for i in range(r["levels"]):
            by_level.setdefault(i + 1, []).append(1 if i < r["cleared"] else 0)
    L.append("\nP0 completion rate by level index (share of game-passes that reached and cleared level k): " +
             ", ".join(f"L{k} {st.mean(v):.0%}" for k, v in sorted(by_level.items()) if k <= 9) + ".\n")

    # 5. per-game table
    L.append("## 5. Per-game mean score by run (mean of 4 passes)\n")
    L.append("| Game | " + " | ".join(RUNS) + " | P0 pass SD |")
    L.append("|---|" + "---|" * len(RUNS) + "---|")
    for g in games:
        L.append(f"| {g} | " + " | ".join(f"{st.mean(r['score'] for r in data[t] if r['game']==g):.1f}" for t in RUNS) + f" | {sdg[g]:.1f} |")

    (OUT / "summary.md").write_text("\n".join(L) + "\n")
    (OUT / "table.json").write_text(json.dumps(T, indent=1))
    print("\n".join(L[:60]))


if __name__ == "__main__":
    main()
